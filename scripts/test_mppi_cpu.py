def test_detection_fixtures_match_the_real_env_sources():
    """The fake attribute bags must name attributes the real envs assign.

    Guards against the detection tests above becoming a tautology: every
    attribute _detect_mode keys on is looked up as a literal ``self.<name> =``
    assignment in the deployed env source. Skipped only when tasks/ is not
    deployed beside scripts/ (the boxes ship the pair alone).
    """
    if not (os.path.exists(DOCKING_ENV_PY) and os.path.exists(HARBOR_ENV_PY)):
        print("\n[NOTE] tasks/ not present; env-source cross-check skipped")
        return
    docking = open(DOCKING_ENV_PY, "r", encoding="utf-8").read()
    harbor = open(HARBOR_ENV_PY, "r", encoding="utf-8").read()
    for name in _DOCK_ATTRS:
        assert re.search(rf"self\.{name}\s*=", docking), (
            f"docking_env.py does not assign self.{name}"
        )
    for name in _MISSION_ATTRS:
        assert re.search(rf"self\.{name}\s*=", harbor), (
            f"harbor_mission_env.py does not assign self.{name}"
        )
    # Neither new env may carry a certified family's key either, or the two
    # branches ahead of them would shadow the berthing cost.
    for name in ("waypoints", "gates_passed", "hold_point", "target_pos"):
        assert not re.search(rf"self\.{name}\s*=", docking), name
        assert not re.search(rf"self\.{name}\s*=", harbor), name
    # ...and the three certified envs must not assign any of them, or a new
    # branch could shadow a certified family on a real task id.
    for relative in (
        os.path.join("path_following", "path_following_env.py"),
        os.path.join("station_keeping", "station_keeping_env.py"),
        os.path.join("hazard_nav", "hazard_nav_env.py"),
    ):
        path = os.path.join(TASKS_DIR, relative)
        if not os.path.exists(path):
            continue
        source = open(path, "r", encoding="utf-8").read()
        for name in _DETECTION_KEYS:
            assert not re.search(rf"self\.{name}\s*=", source), (
                f"{relative} now assigns self.{name}; _detect_mode could "
                "route a certified family into a berthing cost"
            )
    # The evaluator reads the exit-gate sub-state to resolve the active leg.
    assert re.search(r"self\._exit_gate_progress\s*=", harbor), (
        "harbor_mission_env.py no longer has _exit_gate_progress; "
        "eval_mppi._mission_leg would silently take its geometric fallback"
    )
    # HarborStage1/2/3 must really be the SAME env and the SAME route as the
    # full mission, differing only in which milestone scores the episode --
    # that claim is why one mission controller drives all four ids.
    cfg_source = open(
        os.path.join(TASKS_DIR, "harbor_mission", "harbor_mission_env_cfg.py"),
        "r",
        encoding="utf-8",
    ).read()
    for stage in (1, 2, 3):
        block = re.search(
            rf"class HarborStage{stage}EnvCfg\(HarborMissionEnvCfg\):(.*?)\n@",
            cfg_source + "\n@",
            re.S,
        )
        assert block, f"HarborStage{stage}EnvCfg is no longer a plain subclass"
        body = block.group(1)
        assert f"mission_depth: int = {stage}" in body, (
            f"HarborStage{stage} no longer scores milestone M{stage}: {body}"
        )
        for forbidden in ("gate_", "berth", "layout_seed", "spawn_phase"):
            assert forbidden not in body, (
                f"HarborStage{stage} overrides {forbidden!r}: the stages are "
                f"no longer prefixes of the same route -- {body}"
            )


def _record_keys(path: str) -> set[str]:
    """All keys the per-episode ``rec`` object can carry, via AST.

    Collects both the ``rec = {...}`` dict literal's string keys and every
    ``rec["key"] = ...`` subscript assignment, anywhere in the module.
    """
    tree = ast.parse(open(path, "r", encoding="utf-8").read(), filename=path)
    keys: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if (
                isinstance(target, ast.Name)
                and target.id == "rec"
                and isinstance(node.value, ast.Dict)
            ):
                for key in node.value.keys:
                    if isinstance(key, ast.Constant) and isinstance(key.value, str):
                        keys.add(key.value)
            if (
                isinstance(target, ast.Subscript)
                and isinstance(target.value, ast.Name)
                and target.value.id == "rec"
                and isinstance(target.slice, ast.Constant)
                and isinstance(target.slice.value, str)
            ):
                keys.add(target.slice.value)
    return keys


