def test_dock_weight_defaults_match_their_stated_derivation():
    """The two new weights are derived, not fitted -- check the arithmetic.

    Both are quoted at the shipped horizon (H control steps of dt seconds)
    and at the deployed speed tolerance; see the derivation in
    scripts/mppi_controller.py's module docstring.
    """
    params = MPPIParams()
    dt = NOMINAL_BLUEBOAT["physics_dt_s"] * NOMINAL_BLUEBOAT["decimation"]
    v_tol = DOCK_SPEED_TOLERANCE_MPS
    heading = params.w_goal * v_tol * dt * (params.H - 1) / 2.0
    speed = params.w_goal * dt * (params.H - 1) / (2.0 * v_tol)
    assert abs(params.w_dock_heading - heading) < 0.005, (
        f"w_dock_heading {params.w_dock_heading} != derived {heading:.4f}"
    )
    assert abs(params.w_dock_speed - speed) < 0.005, (
        f"w_dock_speed {params.w_dock_speed} != derived {speed:.4f}"
    )
    # The break-even approach speed inside the berth IS the success speed
    # tolerance: at or below 0.3 m/s closing pays, above it slowing pays.
    break_even = dt * (params.H - 1) / (2.0 * params.w_dock_speed)
    assert break_even <= v_tol + 1.0e-3, (
        f"break-even approach speed {break_even:.4f} exceeds the {v_tol} m/s "
        "success tolerance"
    )


