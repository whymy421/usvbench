# 3b-v. The state bridge: WHICH REFERENCE POINT each family is handed
#
# EnvBridge decides what state the controller sees. An adversarial review
# applied three independent mutations to it and every test in this file stayed
# green, so this section exists to fail under each of them:
#
#   N1  feed the certified families the center of mass instead of the
#       reference point they currently get (fallback -> root_com_pos_w)
#   N2  delete the _com_xy helper branch entirely
#   N3  make the docking path read the USD asset origin (dock/mission branch
#       -> root_pos_w)
#
# N3 is the dangerous one and it is not hypothetical: docking scores position
# at the CENTER OF MASS with a 2.5 m tolerance while the boat asset's USD
# origin sits ~1.0 m away (docking_env.py:630-637, "probed 2026-07-16; broke
# both PID and RL"). A 1 m reference-point error is 40% of the tolerance, so
# it buys plausible-looking WRONG docking numbers, not a crash. No docking
# evaluation has been run yet, which is why this is pinned before one is.

# The probed offset between the boat asset's USD body origin and its center of
# mass (docking_env.py:630-637). The stubs below place the two points exactly
# this far apart so a bridge reading the wrong one cannot land on the right
# answer by coincidence.
_ASSET_ORIGIN_OFFSET_M = 1.0

# (family dir, env module, docstring label, bridge mode, publishes _com_xy,
#  the world accessor that family's OWN success predicate ultimately reads).
# test_bridge_reference_points_match_the_env_sources re-derives the last two
# columns from tasks/, so this table is checked against the deployed envs
# rather than asserted.
_REFERENCE_POINT_TRUTH = (
    ("path_following", "path_following_env.py", "PathFollow",
     "gates", False, "root_pos_w"),
    ("path_hazard", "path_hazard_env.py", "PathHazard",
     "gates", True, "root_com_pos_w"),
    ("station_keeping", "station_keeping_env.py", "StationKeep",
     "hold", False, "root_pos_w"),
    ("hazard_nav", "hazard_nav_env.py", "HazardNav",
     "goal", True, "root_com_pos_w"),
    ("docking", "docking_env.py", "Docking",
     "dock", False, "root_com_pos_w"),
    ("harbor_mission", "harbor_mission_env.py", "HarborMission",
     "mission", True, "root_com_pos_w"),
)

# Which families publish the two bow helpers EnvBridge.state() prefers, so the
# stubs take the same code path the real env would. Checked against the
# sources by test_bridge_reference_points_match_the_env_sources.
_FORWARD_2D_FAMILIES = ("hazard_nav", "docking", "harbor_mission")
_ROOT_QUAT_FAMILIES = ("path_hazard", "hazard_nav", "harbor_mission")

# Helpers a success predicate may reach the world accessor through; the
# resolver below follows each one hop until it reaches root_pos_w or
# root_com_pos_w.
_HOP_HELPERS = ("_com_xy", "_horizontal_distance", "_task_state", "_dock_state")


def _env_source_path(family: str, module: str) -> str:
    return os.path.join(TASKS_DIR, family, module)


def _function_bodies(path: str) -> dict:
    source = open(path, "r", encoding="utf-8").read()
    tree = ast.parse(source, filename=path)
    bodies = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            bodies[node.name] = ast.get_source_segment(source, node) or ""
    return bodies


def _world_accessors(body: str) -> set:
    """Which of the two world position accessors this source text reads."""
    found = set()
    if "root_com_pos_w" in body:
        found.add("root_com_pos_w")
    if re.search(r"(?<!com_)root_pos_w", body):
        found.add("root_pos_w")
    return found


def _scored_accessors(bodies: dict, entry: str = "_get_dones") -> set:
    """Resolve the accessor the episode-scoring path ultimately reads."""
    found: set = set()
    pending = [entry]
    seen: set = set()
    while pending:
        name = pending.pop()
        if name in seen or name not in bodies:
            continue
        seen.add(name)
        body = bodies[name]
        found |= _world_accessors(body)
        for helper in _HOP_HELPERS:
            if f"self.{helper}()" in body:
                pending.append(helper)
    return found


def test_bridge_reference_points_match_the_env_sources():
    """Re-derive the reference-point table from tasks/, do not assert it.

    Every claim EnvBridge.position_xy makes about a family is checked here
    against the deployed env source: whether the family publishes _com_xy,
    what _com_xy returns, and which world accessor the block that latches
    episode_success ultimately reads. Skipped only when tasks/ is not
    deployed beside scripts/ (the boxes ship the script pair alone).
    """
    present = [
        row for row in _REFERENCE_POINT_TRUTH
        if os.path.exists(_env_source_path(row[0], row[1]))
    ]
    if not present:
        print("\n[NOTE] tasks/ not present; reference-point cross-check skipped")
        return
    assert len(present) == len(_REFERENCE_POINT_TRUTH), (
        "some env sources are missing; refusing a partial cross-check: "
        f"{sorted(set(r[0] for r in _REFERENCE_POINT_TRUTH) - set(r[0] for r in present))}"
    )
    for family, module, _label, _mode, publishes, scored in present:
        bodies = _function_bodies(_env_source_path(family, module))
        assert ("_com_xy" in bodies) is publishes, (
            f"{family}: publishes _com_xy is {'_com_xy' in bodies}, table "
            f"says {publishes}"
        )
        if publishes:
            assert _world_accessors(bodies["_com_xy"]) == {"root_com_pos_w"}, (
                f"{family}._com_xy no longer returns the center of mass: "
                f"{bodies['_com_xy']}"
            )
        got = _scored_accessors(bodies)
        assert got == {scored}, (
            f"{family}: the success path reads {sorted(got)}, table says "
            f"{scored} -- EnvBridge.position_xy may now hand this family the "
            "wrong reference point"
        )
        assert (family in _FORWARD_2D_FAMILIES) == ("_forward_2d" in bodies), (
            f"{family}: _forward_2d publication drifted from the stub table"
        )
        assert (family in _ROOT_QUAT_FAMILIES) == ("_root_quat" in bodies), (
            f"{family}: _root_quat publication drifted from the stub table"
        )


