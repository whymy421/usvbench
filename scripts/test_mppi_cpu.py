class _FakeEnv:
    """Attribute bag standing in for an Isaac env in _detect_mode only.

    Each fixture below lists the attributes the REAL env of that task id
    publishes; test_detection_fixtures_match_the_real_env_sources checks
    those names against the env sources so this cannot quietly drift into a
    tautology.
    """

    def __init__(self, **attrs):
        for name, value in attrs.items():
            setattr(self, name, value)


