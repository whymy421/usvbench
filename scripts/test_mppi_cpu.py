# 3b. MPPI behavior on the nominal model as the toy world


def _make_controller(n, K=128, H=None, seed=0, **overrides) -> MPPIController:
    """Production defaults except K=128 for CPU runtime (K=256 only samples
    more richly, so the toys validate the shipped H/sigma/lambda)."""
    if H is None:
        H = MPPIParams().H
    params = MPPIParams(K=K, H=H, seed=seed, **overrides)
    return MPPIController(num_envs=n, device=DEVICE, params=params)


def _run_closed_loop(
    controller,
    state,
    targets,
    mode,
    seconds,
    goal_radius=GOAL_RADIUS,
    obstacle_centers=None,
    obstacle_radii=None,
):
    """Execute MPPI against the nominal model as the world; return history."""
    dyn = controller.dynamics
    steps = int(round(seconds / dyn.control_dt_s))
    n = state.shape[0]
    gates_passed = torch.zeros(n, dtype=torch.long)
    num_gates = targets.shape[1]
    trace = {"dist": [], "pos": [], "speed": [], "gates": []}
    for _ in range(steps):
        active = gates_passed.clamp(max=num_gates - 1)
        action, _info = controller.rollout(
            state,
            targets=targets,
            active_index=active,
            goal_radius=goal_radius,
            mode=mode,
            obstacle_centers=obstacle_centers,
            obstacle_radii=obstacle_radii,
        )
        state = dyn.step(state, action)
        pos = state[:, :2]
        tgt = targets.gather(1, active.reshape(n, 1, 1).expand(n, 1, 2)).squeeze(1)
        dist = (pos - tgt).norm(dim=-1)
        if mode != "hold":  # mirror the env's ordered reach rule
            reached = (dist <= goal_radius) & (gates_passed < num_gates)
            gates_passed = gates_passed + reached.long()
