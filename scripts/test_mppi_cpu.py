def test_mppi_mission_runs_the_ordered_chain_and_berths():
    """Three ordered gates then a berth, on the env's own crossing rule.

    Gate legs advance here ONLY when _gate_crossed_local fires, i.e. only
    when the deployed env would have credited the crossing, so "the chain
    completed" is not the controller marking its own homework.
    """
    gates = torch.tensor([[[5.0, 0.0], [15.0, 0.0], [30.0, 0.0]]])
    normals = torch.tensor([[[1.0, 0.0], [1.0, 0.0], [1.0, 0.0]]])
    berth = torch.tensor([[45.0, 0.0]])
    dock_heading = torch.tensor([[1.0, 0.0]])
    route = torch.cat((gates, berth[:, None, :]), dim=1)
    centers = torch.tensor([[[21.0, 0.6], [26.0, -1.3]]])
    radii = torch.tensor([[1.4, 1.2]])

    controller = _make_controller(1, K=64)
    dyn = controller.dynamics
    state = torch.zeros((1, 6))
    leg = torch.zeros(1, dtype=torch.long)
    armed = torch.ones(1, dtype=torch.bool)  # spawn is 5 m before gate 0
    previous = state[:, :2].clone()
    crossings = []
    holds = []
    clearance = math.inf
    for _ in range(int(round(45.0 / dyn.control_dt_s))):
        action, _info = controller.rollout(
            state, targets=route, active_index=leg, goal_radius=BERTH_RADIUS,
            mode="mission", dock_heading=dock_heading, gate_normals=normals,
            obstacle_centers=centers, obstacle_radii=radii,
        )
        state = dyn.step(state, action)
        current = state[:, :2]
        cos_y, sin_y = torch.cos(state[:, 2]), torch.sin(state[:, 2])
        world_v = torch.stack(
            (state[:, 3] * cos_y - state[:, 4] * sin_y,
             state[:, 3] * sin_y + state[:, 4] * cos_y), dim=-1
        )
        clearance = min(clearance, float(
            (current - centers[0]).norm(dim=-1).min()
            - radii.min() - NOMINAL_BLUEBOAT["half_beam_m"]
        ))
        index = int(leg[0])
        if index < 3:
            armed = armed | (
                ((previous - gates[:, index]) * normals[:, index]).sum(-1) <= -1.0
            )
            if bool(_gate_crossed_local(
                previous, current, world_v, gates[:, index], normals[:, index],
                armed,
            )[0]):
                crossings.append(index)
                leg = leg + 1
                nxt = int(leg[0])
                armed = torch.zeros(1, dtype=torch.bool)
                if nxt < 3:
                    armed = armed | (
                        ((current - gates[:, nxt]) * normals[:, nxt]).sum(-1) <= -1.0
                    )
        else:
            holds.append(_dock_success_mask(state, berth, dock_heading))
        previous = current.clone()

    assert crossings == [0, 1, 2], (
        f"ordered chain incomplete or out of order: credited {crossings}"
    )
    assert holds, "the mission never reached its berth leg"
    hold = int(_longest_hold(torch.stack(holds))[0])
    assert hold >= DOCK_HOLD_STEPS, (
        f"berth hold {hold * dyn.control_dt_s:.1f} s of the required "
        f"{DOCK_HOLD_STEPS * dyn.control_dt_s} s"
    )
    assert clearance > 0.0, f"hit the field: min clearance {clearance:.3f} m"


def test_mppi_mission_wrong_side_crossing_earns_no_credit():
    """Flip the gate normal and the same transit stops being a crossing.

    Identical state, identical targets, identical seed and therefore
    identical sampled action sequences; the only change is the SIGN of the
    gate normal, which turns a forward transit into an approach from the
    wrong side. The w_gate credit must vanish with it.
    """
    gate = torch.tensor([[0.0, 0.0]])
    berth = torch.tensor([[20.0, 0.0]])
    route = torch.cat((gate[:, None, :], berth[:, None, :]), dim=1)
    dock_heading = torch.tensor([[1.0, 0.0]])
    state = torch.tensor([[-0.3, 0.0, 0.0, 2.0, 0.0, 0.0]])

    def cost(normal_sign):
        controller = _make_controller(1, K=64, H=20, seed=9)
        _action, info = controller.rollout(
            state, targets=route, active_index=torch.zeros(1, dtype=torch.long),
            goal_radius=BERTH_RADIUS, mode="mission",
            dock_heading=dock_heading,
            gate_normals=torch.tensor([[[normal_sign, 0.0]]]),
        )
        return float(info["cost_min"][0])

    right_way = cost(1.0)
    wrong_way = cost(-1.0)
    params = MPPIParams()
    assert wrong_way - right_way > 0.5 * params.w_gate, (
        f"wrong-side crossing was credited: cost {wrong_way:.2f} vs "
        f"{right_way:.2f} the right way round (w_gate={params.w_gate})"
    )
    # The toy's own rule agrees: same samples, opposite verdict.
    forward = _gate_crossed_local(
        torch.tensor([[-0.3, 0.0]]), torch.tensor([[0.3, 0.0]]),
        torch.tensor([[2.0, 0.0]]), gate, torch.tensor([[1.0, 0.0]]),
        torch.ones(1, dtype=torch.bool),
    )
    backward = _gate_crossed_local(
        torch.tensor([[-0.3, 0.0]]), torch.tensor([[0.3, 0.0]]),
        torch.tensor([[2.0, 0.0]]), gate, torch.tensor([[-1.0, 0.0]]),
        torch.ones(1, dtype=torch.bool),
    )
    assert bool(forward[0]) and not bool(backward[0])


def _mission_gate_cost(state, *, half_width=GATE_HALF_WIDTH_M,
                       min_normal_speed=GATE_MIN_NORMAL_SPEED_MPS):
    """Best rollout cost for one mission step at a single gate, fixed seed.

    One gate at the origin with a +x normal, then a berth 20 m on. Same seed,
    same K/H, same geometry -> the SAME sampled action sequences, so a cost
    difference between two calls is attributable only to the keyword that
    changed.
    """
    gate = torch.zeros((1, 2))
    berth = torch.tensor([[20.0, 0.0]])
