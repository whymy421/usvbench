# 3a. Nominal dynamics sanity


def _rest_state(n: int = 1) -> torch.Tensor:
    return torch.zeros((n, 6))


def _drive(dyn, state, action, seconds: float) -> torch.Tensor:
    steps = int(round(seconds / dyn.control_dt_s))
    a = torch.as_tensor(action, dtype=torch.float32).expand(state.shape[0], 2)
    for _ in range(steps):
        state = dyn.step(state, a)
    return state


def test_dynamics_forward_accelerates_and_caps_at_vmax():
    dyn = NominalBlueBoatDynamics(DEVICE)
    s1 = _drive(dyn, _rest_state(), (1.0, 0.0), 1.0)
    assert float(s1[0, 3]) > 1.0, "full thrust should exceed 1 m/s within 1 s"
    s30 = _drive(dyn, s1, (1.0, 0.0), 29.0)
    cap = dyn.terminal_speed_forward()
    assert abs(cap - 2.991) < 1.0e-3, f"closed-form cap {cap} != 2.991"
    assert abs(float(s30[0, 3]) - cap) < 0.01, (
        f"30 s of full thrust reaches {float(s30[0, 3]):.4f}, cap {cap:.4f}"
    )
    # Straight line: no sway, no yaw, no lateral drift.
    assert abs(float(s30[0, 1])) < 1.0e-4
    assert abs(float(s30[0, 2])) < 1.0e-6
    assert abs(float(s30[0, 4])) < 1.0e-4
    # The repo's own number: usv10k_score.py V_MAX.
    match = re.search(r"V_MAX\s*=\s*([0-9.]+)", open(USV10K).read())
    assert match, "V_MAX not found in usv10k_score.py"
    assert abs(cap - float(match.group(1))) < 1.0e-3


def test_dynamics_reverse_cap_and_asymmetry():
    dyn = NominalBlueBoatDynamics(DEVICE)
    s = _drive(dyn, _rest_state(), (-1.0, 0.0), 30.0)
    cap_rev = dyn.terminal_speed_reverse()
    expected = terminal_speed(48.0, 9.1, 5.9)
    assert abs(cap_rev - expected) < 1.0e-9
    assert abs(float(s[0, 3]) + cap_rev) < 0.01
    assert cap_rev < dyn.terminal_speed_forward(), "reverse must be slower"


def test_dynamics_yaw_terminal_rate_and_turning():
    dyn = NominalBlueBoatDynamics(DEVICE)
    s = _drive(dyn, _rest_state(), (0.0, 1.0), 20.0)
    cap_r = dyn.terminal_yaw_rate()
    assert abs(cap_r - terminal_speed(23.0, 4.0, 6.0)) < 1.0e-9
    assert abs(float(s[0, 5]) - cap_r) < 0.005
    assert float(s[0, 2]) > 3.0, "sustained torque must wind up the heading"
    # Thrust + torque = a curved, bounded turning circle.
    s2 = _drive(dyn, _rest_state(), (1.0, 1.0), 40.0)
    radius_bound = dyn.terminal_speed_forward() / cap_r + 1.0
    assert float(s2[0, :2].norm()) < 4.0 * radius_bound, (
        "hard turn should orbit near the start, not run away"
    )
    assert abs(float(s2[0, 1])) > 0.1, "turning must produce lateral motion"


def test_dynamics_sway_decays():
    dyn = NominalBlueBoatDynamics(DEVICE)
    state = _rest_state()
    state[0, 4] = 1.0  # pure sideways slide
    out = _drive(dyn, state, (0.0, 0.0), 5.0)
    assert abs(float(out[0, 4])) < 0.05, "sway drag must kill lateral speed"
    assert float(out[0, 1]) > 0.0, "the slide still moves the hull first"


