            branch = next(n for n in new.body if isinstance(n, ast.If) and ast.unparse(n.test) == "getattr(self.physics_cfg, 'physics_version', 1) == 1")
            unpack = next(n for n in old.body if isinstance(n, ast.If) and "shape[-1] == 6" in ast.unparse(n.test))
