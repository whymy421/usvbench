        for path in (REPO/"tasks").glob("*/*env_cfg.py"):
            source = path.read_text(encoding="utf-8")
            if "(PhysicsVersionCfg)" not in source: continue
            count += 1
            new = ast.parse(source)
            old = ast.parse((ORIGINAL/path.relative_to(REPO)).read_text(encoding="utf-8"))
            def build(tree):
                node = next(c for c in tree.body if isinstance(c, ast.ClassDef) and c.name in ("UnderwaterPhysicsCfg", "BlueBoatUnderwaterPhysicsCfg"))
                spec_name = "blueboat"
                for n in tree.body:
                    if isinstance(n, ast.Assign) and ast.unparse(n.targets[0]) == "_DEFAULT_VEHICLE":
                        spec_name = n.value.args[0].value
                ns = dict(configclass=dataclasses.dataclass, PhysicsVersionCfg=vehicles.PhysicsVersionCfg, _DEFAULT_VEHICLE=vehicles.get_vehicle(spec_name))
                exec(code([node]), ns)
                return ns[node.name]()
            actual, expected = build(new), build(old)
            self.assertEqual(actual.physics_version, 1)
            actual.physics_version = 2
            self.assertEqual(vehicles.physics_version(actual), 2)
            fields = dataclasses.asdict(actual)
            fields.pop("physics_version")
            self.assertEqual(fields, dataclasses.asdict(expected), str(path))
        self.assertEqual(count, 10)
        for bad in (0, 3, True, "2"):
            with self.assertRaises(ValueError): vehicles.physics_version(NS(physics_version=bad))


