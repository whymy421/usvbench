                values = dict(torch=torch, math_utils=NS(quat_apply_inverse=inv), self=env, quat=q,
                              linear_velocity=torch.randn(5, 3), angular_velocity=torch.randn(5, 3),
                              forces=torch.randn(5, 1, 3), force_w=torch.randn(5, 3), torque_w=torch.randn(5, 3),
                              force_world=torch.randn(5, 3), torque_world=torch.randn(5, 3))
